// สร้าง System Prompt ที่ส่งให้ Claude ทุกครั้ง โดยแทรกข้อมูลร้าน (FAQ/สาขา/รุ่นรถ) แบบสดจาก store.js
"use strict";

const store = require("../services/store");

const BRANCH_LIST_URL = "https://www.taveesubyanyont.com/contactus";
const BKK_PROVINCE_HINTS = ["กรุงเทพ"];

// วันนี้ตามเวลาไทย (UTC+7 ตลอดปี ไม่มี DST) คำนวณจากเวลาเซิร์ฟเวอร์ (Render รันเป็น UTC เสมอ)
// ใช้แทรกลงใน system prompt ให้ Claude มีฐานคำนวณวันที่สัมพัทธ์ (พรุ่งนี้/พุธนี้/อาทิตย์หน้า ฯลฯ) ได้แม่นยำ กันเคสเดาวันที่ผิดไปเป็นวันในอดีต
function getBangkokDateInfo(date = new Date()) {
  const bangkok = new Date(date.getTime() + 7 * 60 * 60 * 1000);
  const y = bangkok.getUTCFullYear();
  const m = String(bangkok.getUTCMonth() + 1).padStart(2, "0");
  const d = String(bangkok.getUTCDate()).padStart(2, "0");
  const days = ["อาทิตย์", "จันทร์", "อังคาร", "พุธ", "พฤหัสบดี", "ศุกร์", "เสาร์"];
  return { iso: `${y}-${m}-${d}`, dayName: days[bangkok.getUTCDay()] };
}

// จัดกลุ่มสาขาตามโซน (กรุงเทพฯ / ปทุมธานี) แบบเดียวกับที่ร้านต้องการนำเสนอให้ลูกค้าเห็นเป็นระเบียบ
// สาขาไหนไม่เข้าเงื่อนไข province กรุงเทพ ให้จัดไปโซนปทุมธานี/อื่นๆ ต่อท้าย
function buildBranchListText(branches) {
  if (!branches.length) return "(ยังไม่มีข้อมูลสาขา)";

  const bkkBranches = branches.filter((b) => BKK_PROVINCE_HINTS.some((hint) => (b.province || "").includes(hint)));
  const otherBranches = branches.filter((b) => !BKK_PROVINCE_HINTS.some((hint) => (b.province || "").includes(hint)));

  const sections = [];
  if (bkkBranches.length) {
    sections.push("โซนกรุงเทพฯ\n" + bkkBranches.map((b) => `- ${b.name}`).join("\n"));
  }
  if (otherBranches.length) {
    const zoneName = otherBranches[0].province || "โซนอื่นๆ";
    sections.push(`โซน${zoneName}\n` + otherBranches.map((b) => `- ${b.name}`).join("\n"));
  }
  return sections.join("\n");
}

// เป็น async เพราะ store.getFaqList()/getActiveBranches()/getModelList() ดึงข้อมูลจาก Google Sheets
// ต้อง await ทุกครั้ง ไม่งั้นจะได้ Promise แทนอาร์เรย์จริง แล้ว .map จะพังทันที
